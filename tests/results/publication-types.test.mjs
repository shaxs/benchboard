import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
test('S4 publication declaration twins and a real production-only API consumer agree',t=>{
  for(const name of ['publication','publication-runtime','artifact-verification'])assert.deepEqual(fs.readFileSync(new URL(`../../packages/results/${name}.d.mts`,import.meta.url)),fs.readFileSync(new URL(`../../packages/results/${name}.d.ts`,import.meta.url)));
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'bb-publication-types-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const mod=fileURLToPath(new URL('../../packages/results/publication.mjs',import.meta.url)).replaceAll('\\','/');
  const reportMod=fileURLToPath(new URL('../../packages/results/report.mjs',import.meta.url)).replaceAll('\\','/');
  const uiMod=fileURLToPath(new URL('../../packages/results/ui-contract.mjs',import.meta.url)).replaceAll('\\','/');
  const runtimeMod=fileURLToPath(new URL('../../packages/results/publication-runtime.mjs',import.meta.url)).replaceAll('\\','/');
  const artifactMod=fileURLToPath(new URL('../../packages/results/artifact-verification.mjs',import.meta.url)).replaceAll('\\','/');
  const consumer=path.join(root,'consumer.mts');
  fs.writeFileSync(consumer,`import {saveReport,readPublishedReport,attachUIReview} from ${JSON.stringify(mod)};
import type {SaveReportRequest,ReadPublishedReportRequest,AttachUIReviewRequest} from ${JSON.stringify(mod)};
import type {Report} from ${JSON.stringify(reportMod)};
import type {UIWorksheet} from ${JSON.stringify(uiMod)};
import {publicationKeysOf,saveReportWithStorageHooks,readPublishedReportInternal,attachUIReviewInternal} from ${JSON.stringify(runtimeMod)};
import {PublicationError,publicationRefusal,assertReportRoots,verifyReportArtifacts} from ${JSON.stringify(artifactMod)};
declare const report:Report;declare const worksheet:UIWorksheet;
const save:SaveReportRequest={storeRoot:'store',runRoot:'run',evaluationRoot:'evidence',report};
const read:ReadPublishedReportRequest={storeRoot:'store',reportId:report.reportId};
const attach:AttachUIReviewRequest={storeRoot:'store',runRoot:'run',evaluationRoot:'evidence',parentReportId:report.reportId,reportId:'new-report',createdAt:'UTC',worksheet,reviewRoot:'review'};
const outputs:Promise<Report>[]=[saveReport(save),readPublishedReport(read),attachUIReview(attach)];
const internal:Promise<Report>[]=[saveReportWithStorageHooks(save,undefined),readPublishedReportInternal(read),attachUIReviewInternal(attach)];
const keyPath:string=publicationKeysOf(report.reportId).report.relativePath;
const errorCode:string=new PublicationError('code','message').code;
const refuse:()=>never=()=>publicationRefusal('code','message');
assertReportRoots(['symbolic-root']);verifyReportArtifacts('symbolic-root',[],{maxFileBytes:1,maxTotalBytes:1});
// @ts-expect-error Public calls never accept injection hooks.
saveReport({...save,hooks:{}});
void [outputs,internal,keyPath,errorCode,refuse];
`);
  const compiler=fileURLToPath(new URL('../../starter/node_modules/typescript/bin/tsc',import.meta.url));
  const result=spawnSync(process.execPath,[compiler,'--noEmit','--strict','--module','NodeNext','--moduleResolution','NodeNext','--target','ES2022',consumer],{encoding:'utf8',timeout:30000,windowsHide:true});
  assert.equal(result.status,0,result.stdout+result.stderr);
});
